def files():
    """The home screen's files, {path inside sistema/web: bytes}."""
    out = {}
    web = os.path.join(ROOT, 'web')
    for base, _, names in os.walk(web):
        for name in sorted(names):
            full = os.path.join(base, name)
            with open(full, 'rb') as f:
                out[os.path.relpath(full, web).replace(os.sep, '/')] = f.read()
    a = os.path.join(ROOT, 'assets')
    with open(os.path.join(a, 'config.json'), encoding='utf-8') as f:
        config = json.load(f)
    with open(os.path.join(a, 'coins.json'), encoding='utf-8') as f:
        coins = json.load(f)
    catalogues = {}
    for name in sorted(os.listdir(os.path.join(a, 'i18n'))):
        if name.endswith('.json'):
            with open(os.path.join(a, 'i18n', name), encoding='utf-8') as f:
                catalogues[name[:-5]] = json.load(f)
    out['config.js'] = ('/* Generated by pc/build.py. */\nwindow.CONFIG = %s;\n' % json.dumps(config, ensure_ascii=False)).encode('utf-8')
    out['coins.js'] = ('window.COINS = %s;\n' % json.dumps(coins)).encode('utf-8')
    out['i18n.js'] = ('/* Generated by pc/build.py from assets/i18n. */\nwindow.I18N_CATALOGUES = %s;\n'
                      % json.dumps(catalogues, ensure_ascii=False, separators=(',', ':'))).encode('utf-8')
    for folder in ('symbols', 'fonts'):
        for name in sorted(os.listdir(os.path.join(a, folder))):
            with open(os.path.join(a, folder, name), 'rb') as f:
                out[folder + '/' + name] = f.read()
    return out


def write_text(path, text, encoding='utf-8-sig'):
    # Windows PowerShell 5.1 reads a file without a BOM as the old Windows code page: written with one, and CRLF
    with open(path, 'w', encoding=encoding, newline='\r\n') as f:
        f.write(text)


def build(out_dir):
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    web = os.path.join(out_dir, 'sistema', 'web')
    for path, content in files().items():
        target = os.path.join(web, path)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'wb') as f:
            f.write(content)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, 'tv.ps1'), encoding='utf-8') as f:
        write_text(os.path.join(out_dir, 'sistema', 'tv.ps1'), f.read())
    with open(os.path.join(here, 'INICIAR-TV.bat'), encoding='utf-8') as f:
        write_text(os.path.join(out_dir, 'INICIAR-TV.bat'), f.read(), 'ascii')
    write_text(os.path.join(out_dir, 'LEIA-ME.txt'), LEIA_ME)
    os.makedirs(os.path.join(out_dir, 'Fundos'))
    write_text(os.path.join(out_dir, 'Fundos', 'LEIA-ME.txt'), FUNDOS)
    shutil.copy(os.path.join(ROOT, 'LICENSE'), os.path.join(out_dir, 'LICENSE.txt'))
    print('Built %s' % out_dir)


def zip_folder(folder, zip_path):
    name = os.path.basename(folder.rstrip(os.sep))
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as z:
        for base, dirs, names in os.walk(folder):
            dirs.sort()
            rel = os.path.relpath(base, folder)
            if not names and rel != '.':
                z.writestr(os.path.join(name, rel).replace(os.sep, '/') + '/', '')
            for n in sorted(names):
                full = os.path.join(base, n)
                z.write(full, os.path.join(name, os.path.relpath(full, folder)).replace(os.sep, '/'))
    print('Zipped %s' % zip_path)


if __name__ == '__main__':
    args = sys.argv[1:]
    out = os.path.abspath(args[args.index('--out') + 1]) if '--out' in args else os.path.join(ROOT, 'out', 'SmartTV')
    build(out)
    if '--zip' in args:
        zip_folder(out, os.path.abspath(args[args.index('--zip') + 1]))
